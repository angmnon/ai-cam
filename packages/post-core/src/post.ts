export function makeProfile(dialect: ControllerProfile["dialect"]): ControllerProfile {
  switch (dialect) {
    case "FANUC":
      return { ...FANUC_PROFILE };
    case "SYNTEC":
      return { ...SYNTEC_PROFILE };
    case "MITSUBISHI":
      return { ...MITSUBISHI_PROFILE };
    default:
      return { ...ISO_GENERIC_PROFILE };
  }
}

/** 由 IR 确定性派生程序号（4 位） */
export function deriveProgramNumber(cam: CamIR, prefix: string): string {
  let h = 0;
  for (const ch of cam.ir_id + cam.part_id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return `${prefix}${1000 + (h % 9000)}`;
}

export function postProcess(cam: CamIR, profile: ControllerProfile): NcProgram {
  const w = new NcWriter(profile, 10);
  const state = createModalState();
  const programNumber = deriveProgramNumber(cam, profile.programPrefix);

  // 程序头（P1-06：校准注入 programHeaderTemplate 时渲染，未校准保持裸程序号）
  w.raw(renderHeader(profile, programNumber, cam));
  w.comment(`GENERATED BY AI-CAM post-core v${profile.post_version}`);
  w.comment(`PART: ${cam.part_id} | JOB: ${cam.job_id} | IR: ${cam.ir_id}`);
  w.comment(`MACHINE: ${cam.machine.machine_name ?? cam.machine.machine_id} | CONTROLLER: ${cam.machine.controller_name ?? cam.machine.controller_id}`);
  w.emit("G21 G17 G90 G94");
  w.emit("G40 G49 G80");

  const toolpaths = new Map<string, ToolpathIR>((cam.toolpaths ?? []).map((tp) => [tp.operation_id, tp]));
  let moveCount = 0;
  let toolChanges = 0;
  let lastToolId: string | null = null;
  // P2-20 / P2-21：WARN 计数器（不抛错，暴露到 metadata）
  const warnings = { unsupportedMoveTypes: 0, coolantFallbacks: 0 };

  for (const op of cam.operations) {
    const tp = toolpaths.get(op.id);
    if (!tp) continue;
    const toolNumber = op.tool.tool_number ?? 1;

    if (lastToolId !== op.tool.tool_id) {
      // 换刀（P1-06：校准注入 toolChangeTemplate 时用模板替换 {tool}）
      w.emit(toolChangeLine(profile, toolNumber));
      if (profile.toolLengthComp) w.emit(`G43 H${toolNumber}`);
      toolChanges++;
      lastToolId = op.tool.tool_id;
      state.currentTool = op.tool.tool_id;
      state.toolNumber = toolNumber;
      state.lastX = null;
      state.lastY = null;
      state.lastZ = null;
      state.lastI = null;
      state.lastJ = null;
      state.lastG = null;
      state.lastF = null;
    }

    // 主轴
    const spindle = Math.round(op.parameters.spindle_speed_rpm);
    if (state.spindleSpeed !== spindle || !state.spindleOn) {
      w.emit(`M03 S${spindle}`);
      state.spindleOn = true;
      state.spindleSpeed = spindle;
    }

    // 冷却
    const coolant = op.parameters.coolant;
    // P2-21：未映射冷却 → 仍 fallback M08（保持 golden 不炸），但 WARN 计数 + 注释
    const mappedCoolant = profile.coolantCodes[coolant];
    if (mappedCoolant == null) {
      warnings.coolantFallbacks++;
      w.comment(`WARN COOLANT FALLBACK ${coolant} -> M08 (op ${op.id})`);
    }
    const code = mappedCoolant ?? "M08";
    if (state.coolant !== coolant) {
      w.emit(code);
      state.coolant = coolant;
    }

    // 刀路（P1-07：DRILL 且方言支持钻孔循环 → G83/G73 模态循环，否则逐行）
    const moves = tp.moves;
    if (op.type === "DRILL" && profile.drillingCycles) {
      moveCount += emitDrillingCycle(moves, state, profile, w, op, warnings);
    } else {
      for (let mi = 0; mi < moves.length; mi++) {
        emitMove(moves[mi], state, profile, w, op, warnings);
        moveCount++;
      }
    }
  }

  // 程序尾
  w.emit("M05");
  state.spindleOn = false;
  if (state.coolant && state.coolant !== "OFF") {
    w.emit("M09");
    state.coolant = "OFF";
  }
  if (profile.homeAtEnd) {
    // P2-22：按方言族回零。Z 轴增量回参考点 → 切绝对 → X/Y 回参考点。
    // FANUC/SYNTEC/ISO 用 G28（第一参考点），MITSUBISHI 用 G30（第二参考点，profile.homeCode）。
    w.emit(`G91 ${profile.homeCode} Z0.`);
    w.emit("G90");
    w.emit(`${profile.homeCode} X0 Y0`);
  }
  w.emit("M30");
  w.raw("%");

  return {
    program_number: programNumber,
    controller_id: cam.machine.controller_id,
    dialect: profile.dialect,
    post_version: profile.post_version,
    text: w.lines.join("\n"),
    lines: w.lines,
    metadata: {
      ir_id: cam.ir_id,
      job_id: cam.job_id,
      part_id: cam.part_id,
      machine_id: cam.machine.machine_id,
      operation_count: cam.operations.length,
      tool_changes: toolChanges,
      move_count: moveCount,
      generated_by: "post-core",
      generator_version: profile.post_version,
      unsupported_move_count: warnings.unsupportedMoveTypes,
      coolant_fallback_count: warnings.coolantFallbacks,
      tool_library_version: profile.toolLibraryVersion ?? "unknown",
      material_version: profile.materialVersion ?? "unknown",
      machine_firmware: profile.machineFirmware ?? "unknown",
    },
  };
}

function emitMove(m: ToolpathMove, state: ModalState, profile: ControllerProfile, w: NcWriter, op: { id: string }, warnings: { unsupportedMoveTypes: number }): string {
  const dec = profile.decimals;
  // P1-06：rapidWord（FANUC/SYNTEC=G0，MITSUBISHI/ISO=G00）与 feed 兜底 defaultFeedMmMin
  const rapidG = profile.rapidWord ?? "G00";
  const feed = m.feed_mm_min ?? (profile.defaultFeedMmMin ?? opFeedFallback(m));
  switch (m.type) {
    case "RAPID": {
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`${rapidG} ${ax}${ax && za ? " " : ""}${za}`.trim());
      return rapidG;
    }
    case "PLUNGE": {
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`G01 ${za}${f}`.trim());
      if (f) state.lastF = feed;
      return "G01";
    }
    case "RETRACT": {
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`${rapidG} ${za}`.trim());
      return rapidG;
    }
    case "LINEAR": {
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      w.emit(`G01 ${ax}${ax && za ? " " : ""}${za}${f}`.trim());
      if (f) state.lastF = feed;
      return "G01";
    }
    case "ARC_CW":
    case "ARC_CCW": {
      const g = m.type === "ARC_CW" ? "G02" : "G03";
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      const i = m.i ?? 0;
      const j = m.j ?? 0;
      const ij = state.lastI !== i || state.lastJ !== j ? ` I${fmt(i, dec)} J${fmt(j, dec)}` : "";
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      w.emit(`${g} ${ax}${ax && za ? " " : ""}${za}${ij}${f}`.trim());
      state.lastI = i;
      state.lastJ = j;
      if (f) state.lastF = feed;
      return g;
    }
    default: {
      // P2-20：未知 move type 不抛错，WARN 计数 + 注释，保持 golden 不炸
      warnings.unsupportedMoveTypes++;
      w.comment(`WARN UNSUPPORTED MOVE TYPE ${m.type} (op ${op.id})`);
      return "UNSUPPORTED";
    }
  }
}

function opFeedFallback(m: ToolpathMove): number {
  // 无进给时按类型给默认（模态一般由 IR 提供）
  return m.type === "PLUNGE" ? 600 : 1200;
}

/** P1-06：换刀行。校准注入 toolChangeTemplate 时替换 {tool}，否则保持 T{n} M06 */
function toolChangeLine(profile: ControllerProfile, toolNumber: number): string {
  if (profile.toolChangeTemplate) {
    return profile.toolChangeTemplate.replace("{tool}", String(toolNumber));
  }
  return `T${toolNumber} M06`;
}

/** P1-06：程序头。校准注入 programHeaderTemplate 时渲染 {program}/{part}/{machine}，否则裸程序号 */
function renderHeader(profile: ControllerProfile, programNumber: string, cam: CamIR): string {
  const t = profile.programHeaderTemplate;
  if (!t) return programNumber;
  const digits = programNumber.slice(profile.programPrefix.length) || programNumber;
  return t
    .replace("{program}", digits)
    .replace("{part}", cam.part_id)
    .replace("{machine}", cam.machine.machine_name ?? cam.machine.machine_id);
}

/** 啄钻每次进给深度兜底（未校准 profile 未注入 peckIncrementMm 时） */
const DEFAULT_PECK_MM = 2.5;
/** G83 孔底暂停 P（ms）兜底 */
const DEFAULT_DWELL_MS = 100;

/**
 * P1-07：钻孔固定循环。op.type=DRILL 且 profile.drillingCycles=true 时调用。
 * 从逐行 PLUNGE/RETRACT 刀路中按 (x,y) 聚合孔位，取最深 PLUNGE Z 为孔底、
 * 最高 RAPID/RETRACT Z 为 R 平面；首孔输出完整 `G83/G73 X Y Z R P Q F`，
 * 后续孔仅 X/Y（模态），最后 G80 取消钻循环模态。
 * 未钻到任何孔（无 PLUNGE）时退回逐行，保证不丢几何。
 *
 * 循环字：校准注入 drillCycle 优先（SYNTEC 默认 G73 高速啄钻）；未校准默认 G83。
 */
function emitDrillingCycle(
  moves: ToolpathMove[],
  state: ModalState,
  profile: ControllerProfile,
  w: NcWriter,
  op: Operation,
  warnings: { unsupportedMoveTypes: number },
): number {
  const dec = profile.decimals;
  const cycle = profile.drillCycle ?? "G83";
  const q = profile.peckIncrementMm ?? DEFAULT_PECK_MM;
  const feedDefault = profile.defaultFeedMmMin ?? 1200;

  const holes = new Map<string, { x: number; y: number; z: number; feed: number }>();
  let rPlane: number | null = null;
  for (const m of moves) {
    if (m.type === "RAPID" || m.type === "RETRACT") {
      if (rPlane == null || m.z > rPlane) rPlane = m.z;
    }
    if (m.type === "PLUNGE") {
      const key = `${m.x.toFixed(dec)},${m.y.toFixed(dec)}`;
      const feed = m.feed_mm_min ?? feedDefault;
      const prev = holes.get(key);
      if (!prev || m.z < prev.z) holes.set(key, { x: m.x, y: m.y, z: m.z, feed });
    }
  }

  if (holes.size === 0) {
    // 兜底：无 PLUNGE → 退回逐行，不丢几何
    let n = 0;
    for (const m of moves) {
      emitMove(m, state, profile, w, op, warnings);
      n++;
    }
    return n;
  }

  const R = rPlane ?? 0;
  const holesArr = [...holes.values()];
  let lines = 0;

  holesArr.forEach((h, idx) => {
    if (idx === 0) {
      w.emit(
        `${cycle} X${fmt(h.x, dec)} Y${fmt(h.y, dec)} Z${fmt(h.z, dec)} R${fmt(R, dec)} P${DEFAULT_DWELL_MS} Q${fmt(q, dec)} F${fmt(h.feed, dec)}`,
      );
      state.lastF = h.feed;
    } else {
      w.emit(`X${fmt(h.x, dec)} Y${fmt(h.y, dec)}`);
    }
    state.lastX = h.x;
    state.lastY = h.y;
    lines++;
  });

  // 钻循环模态用 G80 取消；孔底退回 R 平面
  state.lastZ = R;
  w.emit("G80");
  lines++;
  return lines;
}
