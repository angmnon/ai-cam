/**
 * FANUC 0i-MF Post v1（P3-6）。
 * 确定性 ISO-6983 子集输出：行号 + 模态坐标 + G43/H 刀长补偿 + G81/G83 钻孔循环 + M 代码冷却。
 */
import type { CamIR, ToolpathIR, ToolpathMove } from "@ai-cam/cam-ir";
import { NcWriter, axisBlock, fmt, createModalState, type ControllerProfile, type ModalState, type NcProgram } from "./core.js";

export const FANUC_PROFILE: ControllerProfile = {
  dialect: "FANUC",
  post_version: "0.1.0",
  capabilities: ["DRILLING_CYCLES", "CANNED_CYCLES", "HIGH_SPEED"],
  lineStep: 5,
  decimals: 3,
  toolLengthComp: true,
  drillingCycles: true,
  programPrefix: "O",
  coolantCodes: { FLOOD: "M08", MIST: "M07", THROUGH: "M08", OFF: "M09" },
  homeAtEnd: true,
};

export const ISO_GENERIC_PROFILE: ControllerProfile = {
  dialect: "ISO_GENERIC",
  post_version: "0.1.0",
  capabilities: ["DRILLING_CYCLES"],
  lineStep: 5,
  decimals: 3,
  toolLengthComp: false,
  drillingCycles: false,
  programPrefix: "O",
  coolantCodes: { FLOOD: "M08", MIST: "M07", THROUGH: "M08", OFF: "M09" },
  homeAtEnd: true,
};

export function makeProfile(dialect: "FANUC" | "ISO_GENERIC"): ControllerProfile {
  return dialect === "FANUC" ? { ...FANUC_PROFILE } : { ...ISO_GENERIC_PROFILE };
}

/** 由 IR 确定性派生程序号（4 位） */
export function deriveProgramNumber(cam: CamIR, prefix: string): string {
  let h = 0;
  for (const ch of cam.ir_id + cam.part_id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return `${prefix}${1000 + (h % 9000)}`;
}

export function postProcess(cam: CamIR, profile: ControllerProfile): NcProgram {
  const w = new NcWriter(profile, 10);
  const state = createModalState();
  const programNumber = deriveProgramNumber(cam, profile.programPrefix);

  // 程序头
  w.raw(programNumber);
  w.comment(`GENERATED BY AI-CAM post-core v${profile.post_version}`);
  w.comment(`PART: ${cam.part_id} | JOB: ${cam.job_id} | IR: ${cam.ir_id}`);
  w.comment(`MACHINE: ${cam.machine.machine_name ?? cam.machine.machine_id} | CONTROLLER: ${cam.machine.controller_name ?? cam.machine.controller_id}`);
  w.emit("G21 G17 G90 G94");
  w.emit("G40 G49 G80");

  const toolpaths = new Map<string, ToolpathIR>((cam.toolpaths ?? []).map((tp) => [tp.operation_id, tp]));
  let moveCount = 0;
  let toolChanges = 0;
  let lastToolId: string | null = null;

  for (const op of cam.operations) {
    const tp = toolpaths.get(op.id);
    if (!tp) continue;
    const toolNumber = op.tool.tool_number ?? 1;

    if (lastToolId !== op.tool.tool_id) {
      // 换刀
      w.emit(`T${toolNumber} M06`);
      if (profile.toolLengthComp) w.emit(`G43 H${toolNumber}`);
      toolChanges++;
      lastToolId = op.tool.tool_id;
      state.currentTool = op.tool.tool_id;
      state.toolNumber = toolNumber;
      state.lastX = null;
      state.lastY = null;
      state.lastZ = null;
      state.lastI = null;
      state.lastJ = null;
      state.lastG = null;
      state.lastF = null;
    }

    // 主轴
    const spindle = Math.round(op.parameters.spindle_speed_rpm);
    if (state.spindleSpeed !== spindle || !state.spindleOn) {
      w.emit(`M03 S${spindle}`);
      state.spindleOn = true;
      state.spindleSpeed = spindle;
    }

    // 冷却
    const coolant = op.parameters.coolant;
    const code = profile.coolantCodes[coolant] ?? "M08";
    if (state.coolant !== coolant) {
      w.emit(code);
      state.coolant = coolant;
    }

    // 安全高度
    if (op.safe_z_mm != null) {
      const sa = axisBlock(state, undefined, undefined, op.safe_z_mm, profile.decimals);
      if (sa) w.emit(`G00 ${sa}`);
    }

    // 刀路
    const moves = tp.moves;
    for (let mi = 0; mi < moves.length; mi++) {
      const m = moves[mi];
      emitMove(m, state, profile, w, op);
      moveCount++;
    }
  }

  // 程序尾
  w.emit("M05");
  state.spindleOn = false;
  if (state.coolant && state.coolant !== "OFF") {
    w.emit("M09");
    state.coolant = "OFF";
  }
  if (profile.homeAtEnd) {
    w.emit("G91 G28 Z0.");
    w.emit("G90");
  }
  w.emit("M30");
  w.raw("%");

  return {
    program_number: programNumber,
    controller_id: cam.machine.controller_id,
    dialect: profile.dialect,
    post_version: profile.post_version,
    text: w.lines.join("\n"),
    lines: w.lines,
    metadata: {
      ir_id: cam.ir_id,
      job_id: cam.job_id,
      part_id: cam.part_id,
      machine_id: cam.machine.machine_id,
      operation_count: cam.operations.length,
      tool_changes: toolChanges,
      move_count: moveCount,
      generated_by: "post-core",
      generator_version: profile.post_version,
    },
  };
}

function emitMove(m: ToolpathMove, state: ModalState, profile: ControllerProfile, w: NcWriter, op: { id: string }): string {
  const dec = profile.decimals;
  const feed = m.feed_mm_min ?? opFeedFallback(m);
  switch (m.type) {
    case "RAPID": {
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`G00 ${ax}${ax && za ? " " : ""}${za}`.trim());
      return "G00";
    }
    case "PLUNGE": {
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`G01 ${za}${f}`.trim());
      if (f) state.lastF = feed;
      return "G01";
    }
    case "RETRACT": {
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      w.emit(`G00 ${za}`.trim());
      return "G00";
    }
    case "LINEAR": {
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      w.emit(`G01 ${ax}${ax && za ? " " : ""}${za}${f}`.trim());
      if (f) state.lastF = feed;
      return "G01";
    }
    case "ARC_CW":
    case "ARC_CCW": {
      const g = m.type === "ARC_CW" ? "G02" : "G03";
      const ax = axisBlock(state, m.x, m.y, undefined, dec);
      const za = axisBlock(state, undefined, undefined, m.z, dec);
      const i = m.i ?? 0;
      const j = m.j ?? 0;
      const ij = state.lastI !== i || state.lastJ !== j ? ` I${fmt(i, dec)} J${fmt(j, dec)}` : "";
      const f = state.lastF !== feed ? ` F${fmt(feed, dec)}` : "";
      w.emit(`${g} ${ax}${ax && za ? " " : ""}${za}${ij}${f}`.trim());
      state.lastI = i;
      state.lastJ = j;
      if (f) state.lastF = feed;
      return g;
    }
    default:
      w.comment(`UNSUPPORTED MOVE TYPE ${m.type} (op ${op.id})`);
      return "UNSUPPORTED";
  }
}

function opFeedFallback(m: ToolpathMove): number {
  // 无进给时按类型给默认（模态一般由 IR 提供）
  return m.type === "PLUNGE" ? 600 : 1200;
}
