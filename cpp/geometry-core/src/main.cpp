/**
 * geometry_worker — OCCT 解析与规范化（Phase 1）
 *
 * 用法：
 *   geometry_worker <step-file|->
 *     输出规范化零件模型 JSON（面/边/邻接/healing/tessellation 统计）
 *   geometry_worker <step-file> --obj <out.obj>
 *     额外写出三角化 OBJ（VIEW_MESH 管线，供前端加载）
 *
 * 面输出：id/type/area/bbox/normal(平面) 或 axis+radius(圆柱)/center/edge_count/edges
 * 边输出：id/type/length/face_ids（邻接）
 */
